# 不处理的文件
SKIP_FILES = {'png_rc.py', 'Super_ADB.py'}


def 替换文件(file_path):
    """替换单个文件中的函数名。"""
    text = file_path.read_text(encoding='utf-8')
    changed = False
    for old, new in FUNC_MAP.items():
        # 单词边界替换
        pattern = r'(?<![a-zA-Z0-9_])' + re.escape(old) + r'(?![a-zA-Z0-9_])'
        new_text, count = re.subn(pattern, new, text)
        if count > 0:
            text = new_text
            changed = True
    if changed:
        file_path.write_text(text, encoding='utf-8')
    return changed


def main():
    print('扫描项目文件...')
    py_files = [p for p in WIN_ROOT.rglob('*.py')
                if '__pycache__' not in p.parts and p.name not in SKIP_FILES]
    print(f'  发现 {len(py_files)} 个文件')

    total_changed = 0
    for f in sorted(py_files):
        rel = f.relative_to(WIN_ROOT)
        if 替换文件(f):
            print(f'✓ {rel}')
            total_changed += 1

    print(f'\n完成：修改了 {total_changed} 个文件，{len(FUNC_MAP)} 个函数名映射')


if __name__ == '__main__':
    main()
